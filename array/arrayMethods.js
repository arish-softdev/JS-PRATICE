// Array Method in Javascript

// Push()
let nums = [1, 2, 3, 4, 5];

nums.push(6);
console.log(nums);

// Pop()
let no = [1, 2, 3, 4, 5];

no.pop()
console.log(no);

// Map()
let nos = [1, 2, 3, 4, 5]; 

let doubled = nos.map(n => n * 2);
console.log(doubled);

// Filter()
let number = [1, 2, 3, 4, 5]; 

let even = number.filter(n => n % 2 === 0);
console.log(even);
